  const want = String((window.TRAINER || {}).lang || "en").toLowerCase();
  const lang = DICT[want] ? want : "en";
  const D = DICT[lang];

  const raw = key => (key in D ? D[key] : key in DICT.ru ? DICT.ru[key] : key);
  function t(key, vars) {
    const v = raw(key);
    if (typeof v === "function") return v(vars || {});
    if (typeof v !== "string" || !vars) return v;
    return v.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  }
  // ru: 1 вопрос, 2 вопроса, 5 вопросов (11–14 — «вопросов»); en: 1 question, 2 questions
